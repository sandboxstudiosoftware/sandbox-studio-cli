// exitCodeError carries the exit status of a child process (subshell or command)
// so main can exit with it without printing an error message.
type exitCodeError struct{ code int }

func (e *exitCodeError) Error() string { return fmt.Sprintf("exit status %d", e.code) }

// envVar is one environment variable to set.
type envVar struct{ Name, Value string }

// assumeEnv is the environment change that "assumes" a lease: variables to set and
// variables to remove so nothing else in the environment overrides the credentials.
type assumeEnv struct {
	Set   []envVar
	Unset []string
}

// buildAssumeEnv maps credentials to the standard AWS environment variables. It
// removes AWS_PROFILE and the like, which could otherwise take precedence over
// (or conflict with) the exported keys.
func buildAssumeEnv(pc creds.ProcessCredentials, leaseID string) assumeEnv {
	e := assumeEnv{
		Set: []envVar{
			{"AWS_ACCESS_KEY_ID", pc.AccessKeyID},
			{"AWS_SECRET_ACCESS_KEY", pc.SecretAccessKey},
			{"AWS_SESSION_TOKEN", pc.SessionToken},
			{"AWS_CREDENTIAL_EXPIRATION", pc.Expiration},
			{"SBS_LEASE_ID", leaseID},
		},
		Unset: []string{"AWS_PROFILE", "AWS_DEFAULT_PROFILE", "AWS_SECURITY_TOKEN"},
	}
	return e
}

// sbsExecutable returns the absolute path of the running sbs binary, used as the
// credential_process command. It is a package var so tests can substitute it.
var sbsExecutable = func() (string, error) {
	exe, err := os.Executable()
	if err != nil {
		return "", err
	}
	if resolved, err := filepath.EvalSymlinks(exe); err == nil {
		exe = resolved
	}
	return exe, nil
}

// credentialProcessCommand builds the `sbs creds ...` line the AWS CLI/SDKs run to
// (re)fetch credentials. Global flags are carried over so it hits the same
// deployment.
func credentialProcessCommand(exe, leaseID, role string) string {
	quote := func(s string) string {
		if strings.ContainsAny(s, " \t\"'") {
			return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
		}
		return s
	}
	parts := []string{quote(exe), "creds", "--lease", quote(leaseID)}
	if flagContext != "" {
		parts = append(parts, "--context", quote(flagContext))
	}
	if flagURL != "" {
		parts = append(parts, "--url", quote(flagURL))
	}
	if role != "" && !strings.EqualFold(role, "USER") {
		parts = append(parts, "--role", quote(role))
	}
	return strings.Join(parts, " ")
}

// userAWSConfigPath is the AWS config file the user's tools would read today.
func userAWSConfigPath() string {
	if p := os.Getenv("AWS_CONFIG_FILE"); p != "" {
		return p
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".aws", "config")
}

// profileName is the AWS profile sbs generates for a lease.
func profileName(leaseID string) string { return "sbs-" + leaseID }

// writeLeaseAWSConfig writes an AWS config file for leaseID: a copy of the user's
// own AWS config (so their other profiles keep working) plus a profile whose
// credential_process is `sbs creds`. The AWS CLI and SDKs call it again before the
// credentials expire, so the session is refreshed automatically. The file lives in
// the sbs config dir and is regenerated on every assume.
func writeLeaseAWSConfig(leaseID, credProcess string) (string, error) {
	dir, err := config.Dir()
	if err != nil {
		return "", err
	}
	dir = filepath.Join(dir, "aws")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	var b strings.Builder
	if src := userAWSConfigPath(); src != "" {
		if data, err := os.ReadFile(src); err == nil {
			b.WriteString("# Copied from " + src + "\n")
			b.Write(data)
			if len(data) > 0 && data[len(data)-1] != '\n' {
				b.WriteString("\n")
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("# Generated by `sbs assume` for lease " + leaseID + "\n")
	b.WriteString("[profile " + profileName(leaseID) + "]\n")
	b.WriteString("credential_process = " + credProcess + "\n")
	path := filepath.Join(dir, leaseID+".config")
	if err := os.WriteFile(path, []byte(b.String()), 0o600); err != nil {
		return "", err
	}
	return path, nil
}

// buildProfileEnv points the AWS tools at the generated profile and removes any
// static keys, which would otherwise take precedence over the profile.
func buildProfileEnv(configPath, leaseID string) assumeEnv {
	e := assumeEnv{
		Set: []envVar{
			{"AWS_CONFIG_FILE", configPath},
			{"AWS_PROFILE", profileName(leaseID)},
			{"SBS_LEASE_ID", leaseID},
		},
		Unset: []string{"AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN",
			"AWS_SECURITY_TOKEN", "AWS_CREDENTIAL_EXPIRATION", "AWS_DEFAULT_PROFILE"},
	}
	return e
}

// apply returns base with the change applied.
func (e assumeEnv) apply(base []string) []string {
	drop := map[string]bool{}
	for _, n := range e.Unset {
		drop[n] = true
	}
	for _, v := range e.Set {
		drop[v.Name] = true
	}
	out := make([]string, 0, len(base)+len(e.Set))
	for _, kv := range base {
		name, _, _ := strings.Cut(kv, "=")
		if runtime.GOOS == "windows" {
			name = strings.ToUpper(name)
		}
		if !drop[name] {
			out = append(out, kv)
		}
	}
	for _, v := range e.Set {
		out = append(out, v.Name+"="+v.Value)
	}
	return out
}

// detectShellKind picks the export syntax for the user's shell: posix, fish or
// powershell.
func detectShellKind() string {
	if runtime.GOOS == "windows" {
		return "powershell"
	}
	switch filepath.Base(os.Getenv("SHELL")) {
	case "fish":
		return "fish"
	case "pwsh":
		return "powershell"
	}
	return "posix"
}

// exportScript renders e as statements for `eval "$(sbs assume --export ...)"`.
func (e assumeEnv) exportScript(kind string) (string, error) {
	var b strings.Builder
	switch kind {
	case "posix":
		for _, n := range e.Unset {
			fmt.Fprintf(&b, "unset %s\n", n)
		}
		for _, v := range e.Set {
			fmt.Fprintf(&b, "export %s='%s'\n", v.Name, strings.ReplaceAll(v.Value, "'", `'\''`))
		}
	case "fish":
		for _, n := range e.Unset {
			fmt.Fprintf(&b, "set -e %s\n", n)
		}
		for _, v := range e.Set {
			fmt.Fprintf(&b, "set -gx %s '%s'\n", v.Name, strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(v.Value))
		}
	case "powershell":
		for _, n := range e.Unset {
			fmt.Fprintf(&b, "Remove-Item Env:%s -ErrorAction SilentlyContinue\n", n)
		}
		for _, v := range e.Set {
			fmt.Fprintf(&b, "$env:%s = '%s'\n", v.Name, strings.ReplaceAll(v.Value, "'", "''"))
		}
	default:
		return "", fmt.Errorf("unknown --shell %q: use auto, posix, fish or powershell", kind)
	}
	return b.String(), nil
}

// userShell returns the interactive shell to start for the subshell mode.
func userShell() string {
	if runtime.GOOS == "windows" {
		if p, err := exec.LookPath("pwsh.exe"); err == nil {
			return p
		}
		if p, err := exec.LookPath("powershell.exe"); err == nil {
			return p
		}
		if c := os.Getenv("COMSPEC"); c != "" {
			return c
		}
		return "cmd.exe"
	}
	if s := os.Getenv("SHELL"); s != "" {
		return s
	}
	return "/bin/sh"
}

// runWithEnv runs argv with the assumed environment, wired to our stdio, and
// converts a non-zero exit into an exitCodeError. Ctrl-C is ignored by sbs itself
// while the child runs so it only interrupts the child.
func runWithEnv(e assumeEnv, argv []string) error {
	c := exec.Command(argv[0], argv[1:]...)
	c.Env = e.apply(os.Environ())
	c.Stdin, c.Stdout, c.Stderr = os.Stdin, os.Stdout, os.Stderr
	signal.Ignore(os.Interrupt)
	defer signal.Reset(os.Interrupt)
	if err := c.Run(); err != nil {
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			return &exitCodeError{code: ee.ExitCode()}
		}
		return err
	}
	return nil
}

func newAssumeCmd() *cobra.Command {
	var (
		role   string
		export bool
		shell  string
		static bool
	)
	cmd := &cobra.Command{
		Use:   "assume [lease-id] [-- command [args...]]",
		Short: "Assume the role of a lease: get credentials and set the AWS_* env vars",
		Long: "Sets up your environment so `aws` and any AWS SDK work against a lease's\n" +
			"sandbox account.\n\n" +
			"With no lease id, an interactive list of your Active leases opens; pick one\n" +
			"with enter.\n\n" +
			"A program cannot change its parent shell's environment, so there are three ways\n" +
			"to use the result:\n\n" +
			"  sbs assume [lease]             start a subshell with the credentials (type exit to leave)\n" +
			"  sbs assume [lease] -- aws sts get-caller-identity\n" +
			"                                 run one command with the credentials\n" +
			"  eval \"$(sbs assume --export [lease])\"\n" +
			"                                 set them in your current shell (bash/zsh; use\n" +
			"                                 --shell fish|powershell for others)\n\n" +
			"By default the credentials refresh automatically: sbs writes an AWS profile\n" +
			"whose credential_process is `sbs creds`, and sets AWS_CONFIG_FILE/AWS_PROFILE to\n" +
			"it, so the AWS CLI and SDKs fetch new credentials before they expire. Use\n" +
			"--static to export raw AWS_ACCESS_KEY_ID/... keys instead (for tools that do\n" +
			"not support credential_process); those are not refreshed.",
		Example: "  sbs assume\n" +
			"  sbs assume 3f2a9c1e-...\n" +
			"  sbs assume 3f2a9c1e-... -- aws s3 ls\n" +
			"  eval \"$(sbs assume --export)\"",
		Args: cobra.ArbitraryArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			var command []string
			if dash := cmd.ArgsLenAtDash(); dash >= 0 {
				command = args[dash:]
				args = args[:dash]
			}
			if len(args) > 1 {
				return fmt.Errorf("expected at most one lease id, got %d", len(args))
			}
			if export && len(command) > 0 {
				return fmt.Errorf("--export cannot be combined with a command")
			}
			kind := shell
			if kind == "" || kind == "auto" {
				kind = detectShellKind()
			}
			if export {
				if _, err := (assumeEnv{}).exportScript(kind); err != nil {
					return err
				}
			}

			r, err := normalizeRole(role)
			if err != nil {
				return err
			}

			_, a, err := resolve()
			if err != nil {
				return err
			}
			ctx := context.Background()
			client, err := a.Client(ctx)
			if err != nil {
				return err
			}

			var leaseID string
			if len(args) == 1 {
				leaseID = args[0]
			} else {
				// The picker draws on stderr so --export keeps stdout clean for eval.
				picked, err := pickLease(ctx, client, "assume role")
				if err != nil {
					return err
				}
				if picked == nil {
					fmt.Fprintln(os.Stderr, output.Faint("No lease selected."))
					return &exitCodeError{code: 1}
				}
				leaseID = picked.LeaseID
			}

			if !export && len(command) == 0 && !interactiveTerminal() {
				return fmt.Errorf("not at a terminal: pass a command (`sbs assume <lease> -- cmd`) or use --export")
			}

			// Fetch credentials once up front: this checks access now, while we are
			// at a terminal, and primes the cache the credential_process reads.
			env, expiry, err := assumeLeaseEnv(ctx, a, leaseID, r)
			if err != nil {
				return err
			}
			note := expiryNote(expiry)
			if !static {
				env, err = refreshingEnv(leaseID, r)
				if err != nil {
					return err
				}
				note = "; credentials refresh automatically"
			}

			switch {
			case export:
				script, _ := env.exportScript(kind)
				fmt.Fprint(os.Stdout, script)
				fmt.Fprintf(os.Stderr, "%s Assumed lease %s%s\n", output.Green("✓"), leaseID, note)
				return nil
			case len(command) > 0:
				return runWithEnv(env, command)
			default:
				return runSubshell(env, leaseID, note)
			}
		},
	}
	cmd.Flags().StringVar(&role, "role", "USER", roleFlagHelp)
	cmd.Flags().BoolVar(&export, "export", false, "print shell statements that set the variables, for use with eval")
	cmd.Flags().StringVar(&shell, "shell", "auto", "syntax for --export: auto, posix, fish or powershell")
	cmd.Flags().BoolVar(&static, "static", false, "export raw access keys instead of an auto-refreshing profile (not refreshed)")
	return cmd
}

// assumeLeaseEnv fetches credentials for a lease (via the shared cache) and
// builds the environment change. The returned time is the credentials' expiry
// (zero when unknown).
func assumeLeaseEnv(ctx context.Context, a *auth.Authenticator, leaseID, role string) (assumeEnv, time.Time, error) {
	pc, err := leaseCredentials(ctx, a, leaseID, role)
	if err != nil {
		return assumeEnv{}, time.Time{}, err
	}
	var expiry time.Time
	if t, err := time.Parse(time.RFC3339, pc.Expiration); err == nil {
		expiry = t
	}
	return buildAssumeEnv(pc, leaseID), expiry, nil
}

// refreshingEnv replaces the static keys with an auto-refreshing,
// credential_process-backed profile for the lease.
func refreshingEnv(leaseID, role string) (assumeEnv, error) {
	exe, err := sbsExecutable()
	if err != nil {
		return assumeEnv{}, fmt.Errorf("locating the sbs binary: %w", err)
	}
	path, err := writeLeaseAWSConfig(leaseID, credentialProcessCommand(exe, leaseID, role))
	if err != nil {
		return assumeEnv{}, fmt.Errorf("writing the AWS profile: %w", err)
	}
	return buildProfileEnv(path, leaseID), nil
}

func expiryNote(t time.Time) string {
	if t.IsZero() {
		return ""
	}
	return fmt.Sprintf("; credentials expire %s (in %s)", t.Local().Format("15:04 MST"),
		time.Until(t).Round(time.Minute))
}

func runSubshell(env assumeEnv, leaseID, note string) error {
	sh := userShell()
	fmt.Fprintf(os.Stderr, "%s Assumed lease %s%s\n  Starting %s with AWS credentials set — type `exit` to leave.\n",
		output.Green("✓"), leaseID, note, sh)
	return runWithEnv(env, []string{sh})
}
